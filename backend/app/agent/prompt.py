def build_user_message(question: str, user_name: str, today: str, screen_case_id: str | None) -> str:
    head = f"[오늘: {today} / 사용자: {user_name}]"
    if screen_case_id:
        head += f"\n[지금 보고 있는 사건 ID: {screen_case_id}]"
    return f"{head}\n{question}"


